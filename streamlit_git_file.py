# Libraries
import pandas as pd
import geopandas as gpd
import streamlit as st
import pydeck as pdk
import numpy as np


# Preprocessing
@st.cache_data
@st.cache_data
def preprocess_data(file_path_avg, file_path_cv, shapefile_path):
    # Load both CSVs
    avg_df = pd.read_csv(file_path_avg)
    cv_df = pd.read_csv(file_path_cv)

    shp_gdf = gpd.read_file(shapefile_path)

    # Merge both CSVs with shapefile
    merged_avg = shp_gdf.merge(avg_df, left_on='ID_2', right_on='id2')
    merged_cv = shp_gdf.merge(cv_df, left_on='ID_2', right_on='id2')

    # Simplify geometry
    merged_avg['geometry'] = merged_avg['geometry'].simplify(0.01)
    merged_cv['geometry'] = merged_cv['geometry'].simplify(0.01)

    years = sorted(avg_df['year'].unique())

    return merged_avg, merged_cv, years


from PIL import Image

def make_colorbar():
    # Horizontal gradient: Blue → Purple → Red
    width, height = 256, 20
    colorbar = Image.new("RGBA", (width, height))
    for x in range(width):
        r = int(255 * (x / (width - 1)))
        g = 120
        b = int(255 * (1 - x / (width - 1)))
        for y in range(height):
            colorbar.putpixel((x, y), (r, g, b, 255))
    return colorbar

# Computation of density function - for plot
def kde_1d(data, num_points=200, bandwidth=None):
    data = np.asarray(data)
    data = data[~np.isnan(data)]

    # Silverman's rule of thumb if no bandwidth provided
    if bandwidth is None:
        bandwidth = 1.06 * data.std() * len(data) ** (-1/5)

    xs = np.linspace(data.min(), data.max(), num_points)
    density = np.zeros_like(xs)

    for x in data:
        density += np.exp(-0.5 * ((xs - x) / bandwidth) ** 2)

    density /= (len(data) * bandwidth * np.sqrt(2 * np.pi))
    return xs, density

FEATURE_UNITS = {
    "yield": "bu/acre",
    "tmmx": "K", 
    "tmmn": "K",
    "rmax": "%", 
    "rmin": "%", 
    "sph": "g/kg",
    "vpd": "kPa",
    "pr": "kg/m²",
    "srad": "W/m²",
    "vs": "m/s",
    "th": "°"
}


# Choropleth plotting function
def plot_choropleth(gdf, feature, year):
    # Filter for selected year
    gdf_year = gdf[gdf['year'] == year].copy()

    # Feature-specific scaling (important)
    min_val = gdf_year[feature].min()
    max_val = gdf_year[feature].max()

    gdf_year["__norm"] = (gdf_year[feature] - min_val) / (max_val - min_val + 1e-9)
    gdf_year["color"] = gdf_year["__norm"].apply(lambda x: [int(255 * x), 120, int(255 * (1 - x)), 180])

    gdf_year["value_disp"] = gdf_year[feature].round(4)
    
    layer = pdk.Layer(
        "GeoJsonLayer",
        gdf_year,
        opacity=0.75,
        stroked=True,
        filled=True,
        get_fill_color="color",
        get_line_color=[0, 0, 0],
        pickable=True,
    )

    view_state = pdk.ViewState(
        latitude=40.0,
        longitude=-93.0,
        zoom=4,
        pitch=0,
    )
    r = pdk.Deck(
        layers=[layer],
        initial_view_state=view_state,
        tooltip={
            "html": "<b>{NAME_2}</b><br>" + feature + ": {value_disp}",
            "style": {"backgroundColor": "white", "color": "black"}
        },
)


    # Layout: map left, scale right
    left, right = st.columns([4, 1])

    with left:
        st.pydeck_chart(r)
        st.caption(f"Showing **{feature}** for **{year}**")

        # Show horizontal gradient
        st.image(make_colorbar(), use_column_width=True)
        
        # Get units (default: "")
        unit = FEATURE_UNITS.get(feature, "")
        
        # Build formatted labels
        min_label = f"{min_val:.4f} {unit}"
        max_label = f"{max_val:.4f} {unit}"
        
        # Show left/right labels under the colorbar
        cols = st.columns([1, 1])
        cols[0].markdown(f"**{min_label}**")
        cols[1].markdown(f"<div style='text-align:right'><b>{max_label}</b></div>", unsafe_allow_html=True)


    # Display key statistics
    with right:
        st.write("### Values")
        st.metric("Minimum", f"{min_val:.4f}")
        st.metric("Maximum", f"{max_val:.4f}")
        st.metric("Mean", f"{gdf_year[feature].mean():.4f}")
        st.metric("Median", f"{gdf_year[feature].median():.4f}")

    st.write(f"### Distribution of {feature} in {year}")
    
    vals = gdf_year[feature].dropna()
    xs, density = kde_1d(vals)
    
    density_df = pd.DataFrame({"value": xs, "density": density})
    density_df = density_df.set_index("value") 

    # Display density plot
    st.area_chart(density_df)





# Streamlit App
def main():
    st.set_page_config(layout="wide")
    st.title("US Corn Belt Yield Dashboard")

    st.text("Welcome to the dashboard!")
    st.text("Select 'Explore' to view the feature and yield values county by county or 'Model Builder' to build your own regression model!")

    file_path_avg = "all_feature_data_avg.csv"
    file_path_cv = "all_feature_data_coeff_of_variation.csv"
    shapefile_path = "CornBeltCounty.shp"

    # Load data
    merged_avg, merged_cv, years = preprocess_data(file_path_avg, file_path_cv, shapefile_path)

    # Sidebar: select active tab
    # active_tab = st.sidebar.radio("Select App Section", ["Exploration", "Model Builder"])
    tab1, tab2, tab3 = st.tabs(["Exploration", "Model Builder", "Data Dictionary"])

    # Exploration Sidebar Controls
    # Tabs

    # Tab 1: Exploration
    with tab1:
        st.header("Exploration Controls")
        col1, col2 = st.columns([1,2])
        with col1:
            dataset_choice = st.selectbox(
                "Dataset Type",
                ["Mean", "Coefficient of Variation"]
            )

            if dataset_choice == "Mean":
                active_gdf = merged_avg
            else:
                active_gdf = merged_cv

            year = st.slider(
                "Select Year",
                min_value=min(years),
                max_value=max(years),
                value=max(years)
            )

            cols_to_use = [
                'yield', 'tmmx', 'rmax', 'vs', 'sph', 'srad',
                'vpd', 'rmin', 'pr', 'tmmn', 'th'
            ]
            feature = st.selectbox("Select Feature", cols_to_use, index=0)
        st.divider()

        tab1.header(f"{dataset_choice}: {feature.title()} Map - {year}")
            # st.header(f"{dataset_choice}: {feature.title()} Map - {year}")
        plot_choropleth(active_gdf, feature, year)
        # else:
            # st.info("Switch to Exploration tab to see observed data.")

    # Tab 2: Model Builder
    with tab2:
        st.header("Model Builder Controls")

        # Predictor features (exclude 'yield')
        predictor_features = [
            'tmmx', 'rmax', 'vs', 'sph', 'srad',
            'vpd', 'rmin', 'pr', 'tmmn', 'th'
        ]

        col1, col2 = st.columns([1,2])
        with col1:
            model_features = st.multiselect(
                "Select Features for Regression:",
                predictor_features,
                default=['tmmx', 'rmax', 'pr']
            )

            # Hyperparameters
            alpha = st.number_input(
                "Alpha (regularization strength)",
                min_value=0.0,
                value=1.0,     # default
                step=0.1,
                format="%.4f"
            )

            # Only show l1_ratio slider if Elastic Net is selected
            if model_choice == "Elastic Net":
                l1_ratio = st.number_input(
                    "L1 Ratio (Elastic Net only)",
                    min_value=0.0,
                    max_value=1.0,
                    value=0.5,      # default
                    step=0.05,
                    format="%.2f"
                )
            else:
                l1_ratio = None

            model_choice = st.selectbox(
                "Select Model Type:",
                ["Ridge", "Lasso", "Elastic Net"]
            )
        
            pred_year = st.selectbox(
                "Select Year to Visualize Predictions:",
                years,
                index=len(years)-1
            )

        st.divider()

        if len(model_features) == 0:
            st.sidebar.warning("Please select at least one feature.")
            st.stop()
        # if active_tab != "Model Builder":
            # st.info("Switch to Model Builder tab to run the model.")
            # st.stop()
        
        st.header("Yield Prediction Model (LOYO Ridge)")
        st.write("Predictions are made using leave-one-year-out cross-validation.")

        # Prepare data
        df = merged_avg.drop(columns="geometry").copy()

        # LOYO Regression
        from sklearn.linear_model import Ridge
        from sklearn.metrics import mean_squared_error, mean_absolute_error
        import numpy as np
        from sklearn.linear_model import Ridge, Lasso, ElasticNet
        from sklearn.metrics import mean_squared_error, mean_absolute_error
        
        predictions = []
        metrics = []

        years_unique = sorted(df["year"].unique())

        for yr in years_unique:
            train = df[df["year"] != yr]
            test = df[df["year"] == yr]

            X_train = train[model_features].values
            y_train = train["yield"].values
            X_test = test[model_features].values
            y_test = test["yield"].values

            # Select model based on user choice
            if model_choice == "Ridge":
                model = Ridge(alpha=alpha)
            
            elif model_choice == "Lasso":
                model = Lasso(alpha=alpha)
            
            elif model_choice == "Elastic Net":
                model = ElasticNet(alpha=alpha, l1_ratio=l1_ratio)
            
            # Train + predict
            model.fit(X_train, y_train)
            y_pred = model.predict(X_test)


            # Store predictions
            temp = test[["id2", "year"]].copy()
            temp["predicted_yield"] = y_pred
            predictions.append(temp)

            # Metrics
            mse = mean_squared_error(y_test, y_pred)
            rmse = np.sqrt(mse)
            mae = mean_absolute_error(y_test, y_pred)
            metrics.append({"year": yr, "rmse": rmse, "mae": mae})

        predictions_df = pd.concat(predictions)
        metrics_df = pd.DataFrame(metrics)

        st.subheader("Model Performance (LOYO)")
        st.dataframe(metrics_df)

        # Filter predictions for user-selected year
        plot_gdf = merged_avg.merge(
            predictions_df[predictions_df["year"] == pred_year],
            on=["id2", "year"],
            how="left"
        )

        st.subheader(f"Predicted Yield Map – {pred_year}")
        plot_choropleth(plot_gdf, "predicted_yield", pred_year)
    # Tab 3: Data Dictionary
    with tab3:
        st.header("Data Dictionary")
    
        st.markdown("""
        ### Climate & Environmental Variables
    
        **sph — Near-Surface Specific Humidity (g/kg)**  
        Amount of water vapor contained in the air.
    
        **vpd — Mean Vapor Pressure Deficit (kPa)**  
        Measures the "drying power" of air — higher VPD = more evaporative demand.
    
        **pr — Precipitation (kg/m²)**  
        Total precipitation amount.
    
        **rmin — Minimum Near-Surface Relative Humidity (%)**  
        The minimum daily percent of water vapor in the air relative to how much could be held at that temperature.
    
        **rmax — Maximum Near-Surface Relative Humidity (%)**  
        The maximum daily percent of water vapor in the air relative to capacity.
    
        **srad — Surface Downwelling Solar Radiation (W/m²)**  
        How much sunlight reaches the ground.
    
        **tmmn — Minimum Near-Surface Air Temperature (°C)**  
        Daily minimum temperature.
    
        **tmmx — Maximum Near-Surface Air Temperature (°C)**  
        Daily maximum temperature.
    
        **vs — Wind Speed at 10 m (m/s)**  
        Average wind speed measured 10 meters above ground.
    
        **th — Wind Direction at 10 m (degrees)**  
        Direction from which the wind blows.
        """)
    
        st.info("These definitions follow standard climatology and meteorology conventions commonly used in agricultural modeling.")



# Run App
if __name__ == "__main__":
    main()
